"""Copy the Lua runtime prelude + level template of the Python mission translator into the C++ port.

    python scripts/sync_m2l_runtime.py [--modkit <ConflictDesertStormModKit>] [--check]

The generated Lua of a mission DLL (docs/internal/mission-translation.md) starts with a runtime prelude (registers, lazy
flags, x87 stack, call helpers) and ends with a level template (init / detach). Both are OUR code and live as text in
ModKit conflict_ds_tools/mission2lua.py (RUNTIME, MAIN, VERSION). The C++ port (pse/build/mission2lua) must write the
same text, so this script writes them into pse/build/mission2lua/m2l_runtime.inc (committed; no game code in it).
--check: exit 1 when the .inc is out of date (the gate, tools/m2l_gate.py, runs it first).
"""
import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "pse", "build", "mission2lua", "m2l_runtime.inc")


def chunks(text, limit=8000):
    out, cur = [], ""
    for line in text.splitlines(keepends=True):
        if len(cur) + len(line) > limit and cur:
            out.append(cur)
            cur = ""
        cur += line
    if cur:
        out.append(cur)
    return out


def literal(parts):
    for p in parts:
        assert ')m2l"' not in p
    return "\n".join('    R"m2l(%s)m2l",' % p for p in parts)


def render(m):
    rt, main = m.RUNTIME, m.MAIN
    digest = hashlib.sha256((rt + "\0" + main + "\0" + str(m.VERSION)).encode("utf-8")).hexdigest()
    return (
        "// Generated by scripts/sync_m2l_runtime.py from ModKit conflict_ds_tools/mission2lua.py - do not edit.\n"
        "// RUNTIME (prelude, %%VERSION%% replaced), MAIN (level template, Python %%-format) and VERSION of the translator.\n"
        "// source digest %s\n"
        "constexpr int kTranslatorVersion = %d;\n"
        "constexpr const char* kRuntimeParts[] = {\n%s\n    nullptr};\n"
        "constexpr const char* kMainParts[] = {\n%s\n    nullptr};\n"
    ) % (digest, m.VERSION, literal(chunks(rt)), literal(chunks(main)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--modkit", default=os.path.join(os.path.dirname(REPO), "ConflictDesertStormModKit"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sys.path.insert(0, a.modkit)
    from conflict_ds_tools import mission2lua as m
    text = render(m)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if a.check:
        if old != text:
            print("m2l_runtime.inc is out of date - run scripts/sync_m2l_runtime.py")
            return 1
        print("m2l_runtime.inc up to date (translator version %d)" % m.VERSION)
        return 0
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s (translator version %d)" % (OUT, m.VERSION))
    else:
        print("unchanged (translator version %d)" % m.VERSION)
    return 0


if __name__ == "__main__":
    sys.exit(main())
