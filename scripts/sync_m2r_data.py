"""Copy the data of the Python readable mission translator into the C++ port.

    python scripts/sync_m2r_data.py [--modkit <ConflictDesertStormModKit>] [--check]

The readable translator (ModKit conflict_ds_tools/mission2lua_readable.py, C++ port pse/build/mission2lua/m2r_*.cpp)
names the script API from the ModKit's editor/games/ds1/api_slots.json (name, arguments, return text), the game messages
from editor/missionlogic.py MESSAGES, and writes its bridge (BRIDGE) and level start (MAIN) as text. All of it is OUR
data / code, so this script writes it into pse/build/mission2lua/m2r_data.inc (committed; no game code in it).
--check: exit 1 when the .inc is out of date (scripts/m2r_gate.py runs it first).
"""
import argparse
import ast
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "pse", "build", "mission2lua", "m2r_data.inc")


def cstr(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def chunks(text, limit=8000):
    out, cur = [], ""
    for line in text.splitlines(keepends=True):
        if len(cur) + len(line) > limit and cur:
            out.append(cur)
            cur = ""
        cur += line
    if cur:
        out.append(cur)
    return out


def raw(parts):
    for p in parts:
        assert ')m2r"' not in p
    return "\n".join('    R"m2r(%s)m2r",' % p for p in parts)


def render(modkit):
    sys.path.insert(0, modkit)
    from conflict_ds_tools import mission2lua_readable as m
    with open(m.SLOTS_JSON, encoding="utf-8") as f:
        slots = json.load(f)
    src = open(os.path.join(modkit, "editor", "missionlogic.py"), encoding="utf-8").read()
    msgs = ast.literal_eval(re.search(r"^MESSAGES = (\{.*?^\})", src, re.S | re.M).group(1))
    lines = []
    for k in sorted(slots, key=lambda x: int(x, 16)):
        v = slots[k]
        args = v.get("args")
        a = "{%s}" % ", ".join("{%s, %s}" % (cstr(x.get("name") or ""), cstr(x.get("type") or "")) for x in args or [])
        lines.append("    {0x%03X, %s, %s, %s, %s, %s}," % (
            int(k, 16), cstr(v.get("name") or ""), "true" if "args" in v else "false", a,
            "true" if "returns" in v else "false", cstr(str(v.get("returns") or ""))))
    mlines = []
    for mid in msgs:   # (source order: the translator iterates the dict)
        name, desc, params = msgs[mid]
        mlines.append("    {0x%02X, %s, %s, {%s}}," % (mid, cstr(name), cstr(desc), ", ".join(cstr(p) for p in params)))
    digest = hashlib.sha256(json.dumps([slots, repr(msgs), m.BRIDGE, m.MAIN, m.VERSION], sort_keys=True)
                            .encode("utf-8")).hexdigest()
    return (
        "// Generated by scripts/sync_m2r_data.py from ModKit conflict_ds_tools/mission2lua_readable.py,\n"
        "// editor/games/ds1/api_slots.json and editor/missionlogic.py MESSAGES - do not edit.\n"
        "// source digest %s\n"
        "constexpr int kReadableVersion = %d;\n"
        "struct SlotRow {\n    int slot;\n    const char* name;\n    bool hasArgs;\n"
        "    std::vector<std::pair<const char*, const char*>> args;\n    bool hasReturns;\n    const char* returns;\n};\n"
        "inline const std::vector<SlotRow>& SlotRows() {\n    static const std::vector<SlotRow> rows = {\n%s\n    };\n"
        "    return rows;\n}\n"
        "struct MsgRow {\n    int id;\n    const char* name;\n    const char* desc;\n    std::vector<const char*> params;\n};\n"
        "inline const std::vector<MsgRow>& MsgRows() {\n    static const std::vector<MsgRow> rows = {\n%s\n    };\n"
        "    return rows;\n}\n"
        "constexpr const char* kBridgeParts[] = {\n%s\n    nullptr};\n"
        "constexpr const char* kMainParts[] = {\n%s\n    nullptr};\n"
    ) % (digest, m.VERSION, "\n".join(lines), "\n".join(mlines), raw(chunks(m.BRIDGE)), raw(chunks(m.MAIN)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--modkit", default=os.path.join(os.path.dirname(REPO), "ConflictDesertStormModKit"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(a.modkit)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if a.check:
        if old != text:
            print("m2r_data.inc is out of date - run scripts/sync_m2r_data.py")
            return 1
        print("m2r_data.inc up to date")
        return 0
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(OUT, REPO))
    else:
        print("m2r_data.inc unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
