"""Generate src/generated/standard_anims.h: the animation table every mission script registers.

Each MissionN.dll registers ~200 animation states through script API +0x04 (state name, .prs file) during its init
(Mission 2 and 4-10: the same 203; Mission 1 / 3 / 5A / 11 add a few cutscene ones, Training swaps 16). Lua mission
scripts (scripthost.cpp) get this table registered for them (+ the ladder states when the scene has ladders) and add level-specific states with game.anim().

Usage: python scripts/gen_standard_anims.py <game dir>   (reads Mission2.dll; needs pefile + capstone)
"""
import os, re, sys
import capstone, pefile

if len(sys.argv) < 2:
    sys.exit(__doc__)
game = sys.argv[1]
dll = os.path.join(game, "Mission2.dll")
out = os.path.join(os.path.dirname(__file__), "..", "src", "generated", "standard_anims.h")

p = pefile.PE(dll); ib = p.OPTIONAL_HEADER.ImageBase; img = p.get_memory_mapped_image()
t = [s for s in p.sections if s.Name.startswith(b".text")][0]
base = ib + t.VirtualAddress; code = img[t.VirtualAddress:t.VirtualAddress + t.Misc_VirtualSize]
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)

def cstr(a):
    o = a - ib
    if 0 <= o < len(img):
        s = img[o:img.find(b"\0", o)]
        if 0 < len(s) < 80 and all(32 <= c < 127 for c in s): return s.decode()

pairs, pushes, pos = [], [], 0
while pos < len(code):
    got = False
    for i in md.disasm(code[pos:], base + pos):
        got = True; pos = i.address - base + i.size
        if i.mnemonic == "push": pushes.append(i.op_str)
        elif i.mnemonic == "call":
            # api+4(state, file): cdecl, so the file is pushed first
            if re.match(r"dword ptr \[e[a-z]{2} \+ 4\]$", i.op_str) and len(pushes) >= 2:
                state, file = (cstr(int(x, 16)) if x.startswith("0x") else None for x in (pushes[-1], pushes[-2]))
                if state and file and (state, file) not in pairs: pairs.append((state, file))
            pushes = []
    if not got: pos += 1

# The ladder states are registered separately, after the scene loads and only when API +0x70 reports ladders
# (Mission1.dll 0x10008FB0) - their .prs files are only in the archives of levels with ladders.
ladder = [x for x in pairs if "LADDER" in x[0]]
pairs = [x for x in pairs if "LADDER" not in x[0]]

with open(out, "w", newline="\n") as f:
    f.write("// Generated by scripts/gen_standard_anims.py from Mission2.dll - do not edit.\n")
    f.write("// Animation states every mission script registers (script API +0x04: state, .prs file).\n#pragma once\n\n")
    f.write("namespace generated {\nstruct StandardAnim { const char* state; const char* file; };\n")
    f.write("inline constexpr StandardAnim kStandardAnims[] = {\n")
    for s, fl in pairs: f.write(f'    {{"{s}", "{fl}"}},\n')
    f.write("};\n// Registered after the scene when API +0x70 returns non-zero (levels with ladders).\n")
    f.write("inline constexpr StandardAnim kLadderAnims[] = {\n")
    for s, fl in ladder: f.write(f'    {{"{s}", "{fl}"}},\n')
    f.write("};\n}  // namespace generated\n")
print(f"{len(pairs)} + {len(ladder)} ladder animations -> {os.path.normpath(out)}")
